// Writes public/THIRD_PARTY_NOTICES.txt from the license files of every production
// dependency, so the bundle served to browsers carries the copyright and permission
// notices that MIT, BSD and ISC require. Runs before every `npm run build`.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const npmCli = process.env.npm_execpath;
const args = ["ls", "--omit=dev", "--all", "--parseable"];

function listDependencies() {
  try {
    // Prefer the npm that is running this script (works when PATH shims are unusable).
    return npmCli
      ? execFileSync(process.execPath, [npmCli, ...args], { cwd: root, encoding: "utf8" })
      : execFileSync("npm", args, { cwd: root, encoding: "utf8", shell: true });
  } catch (err) {
    // `npm ls` exits non-zero when node_modules disagrees with package.json but still
    // prints the tree. CI installs with `npm ci`, where this never happens.
    if (err && typeof err.stdout === "string" && err.stdout.trim()) {
      console.warn("notices: npm ls reported problems (run `npm ci`); using the installed tree");
      return err.stdout;
    }
    throw err;
  }
}
const output = listDependencies();

const dirs = [...new Set(output.split(/\r?\n/).filter((d) => d && d !== root))].sort();
const sections = [];
for (const dir of dirs) {
  const pkgFile = join(dir, "package.json");
  if (!existsSync(pkgFile)) continue;
  const pkg = JSON.parse(readFileSync(pkgFile, "utf8"));
  const licenseFile = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  const text = licenseFile
    ? readFileSync(join(dir, licenseFile), "utf8").trim()
    : `License: ${typeof pkg.license === "string" ? pkg.license : "see package"} (no license file in the package)`;
  sections.push(`${pkg.name}@${pkg.version} (${pkg.license ?? "unknown"})\n\n${text}`);
}

const header =
  "Third-party software bundled into this web application.\n" +
  "Generated by web/scripts/notices.mjs from the production dependencies.\n";
writeFileSync(
  join(root, "public", "THIRD_PARTY_NOTICES.txt"),
  `${header}\n${"=".repeat(78)}\n\n${sections.join(`\n\n${"=".repeat(78)}\n\n`)}\n`,
);
console.log(`THIRD_PARTY_NOTICES.txt: ${sections.length} packages`);
